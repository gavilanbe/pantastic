// Capturas del selector de protagonista y de una partida con Isart. Uso: node tools/pick.mjs [carpeta]
import { chromium } from 'playwright';
import { spawn } from 'node:child_process';
import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.resolve(root, process.argv[2] || 'shots/pick'); fs.mkdirSync(out, { recursive: true });
const port = 5190 + Math.floor(Math.random() * 300);
const srv = spawn('node', [path.join(root, 'tools/serve.mjs'), String(port)], { stdio: 'ignore' });
await new Promise(r => setTimeout(r, 400));
const cacheDir = process.env.HOME + '/Library/Caches/ms-playwright';
const exe = fs.readdirSync(cacheDir).filter(d => d.startsWith('chromium_headless_shell-')).sort().map(d => `${cacheDir}/${d}/chrome-headless-shell-mac-arm64/chrome-headless-shell`).filter(f => fs.existsSync(f)).pop();
const browser = await chromium.launch({ executablePath: exe, args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 1 }); let bad = 0;
page.on('console', m => { if (m.type() === 'error') { bad++; console.log('[error]', m.text()); } });
page.on('pageerror', e => { bad++; console.log('[pageerror]', e.message, e.stack?.split('\n').slice(0, 4).join('\n')); });
const shot = async (n) => { await page.screenshot({ path: path.join(out, n + '.png') }); console.log('captura', n); };
await page.goto(`http://127.0.0.1:${port}/`); await page.waitForFunction('window.game && window.game.ready'); await page.waitForTimeout(1200);
await page.keyboard.press('e'); await page.waitForTimeout(2600); await shot('01-foco-pan');
await page.waitForTimeout(1500); await shot('02-foco-pan-gesto');
await page.keyboard.press('d'); await page.waitForTimeout(1400); await shot('03-foco-isart');
await page.waitForTimeout(2100); await shot('04-foco-isart-gesto');
await page.keyboard.press('e'); await page.waitForTimeout(900); await shot('05-elegido');
await page.waitForTimeout(3200); await shot('06-carta');
await page.keyboard.press('e'); await page.waitForTimeout(4500); await shot('07-dia1-isart');
console.log('héroe:', await page.evaluate(() => window.game.S.hero), 'modo:', await page.evaluate(() => window.game.mode));
await page.evaluate(() => { window.game.cam.zoomTo = 0.3; window.game.tp(1.6, -1.4, 0); }); await page.waitForTimeout(1600); await shot('08-isart-cerca');
await page.evaluate(() => { window.game.tp(1.6, -1.4, Math.PI); window.game.pan.yawTo = Math.PI; }); await page.waitForTimeout(900); await shot('09-isart-espalda');
console.log(bad ? `${bad} problema(s)` : 'todo bien'); await browser.close(); srv.kill(); process.exit(bad ? 1 : 0);
